using Microsoft.Extensions.Hosting;

namespace MyPetLink.Api.Common;

/// <summary>
/// The official-looking MyPetLink demo identity used to film launch material,
/// bound from the "MarketingDemo" configuration section.
///
/// Deployment-owned rather than admin-editable: this decides whether a host
/// fabricates an account at all, which is a property of the machine, not of the
/// business. Per the configuration governance rules it has exactly one owner and
/// no duplicate elsewhere.
///
/// <b>It can only ever be true on a developer's machine.</b> Three independent
/// switches have to agree — <c>IsDevelopment()</c>, the <c>DevAuth</c> opt-in,
/// and this one — and <see cref="ValidateForStartup"/> refuses to start a
/// non-Development host that has it enabled, rather than quietly ignoring it.
/// A misconfigured deployment is then a failure at boot instead of a brand
/// account appearing in production.
/// </summary>
public sealed class MarketingDemoOptions
{
    public const string SectionName = "MarketingDemo";

    public bool Enabled { get; init; }

    /// <summary>
    /// Where the demo's pictures are served from.
    ///
    /// Demo media deliberately does NOT go through the ordinary upload path.
    /// That path signs an upload straight into the configured Cloudflare R2
    /// bucket, and a local machine is usually pointed at the real one — so
    /// seeding through it would publish marketing fixtures to production
    /// storage and to the live CDN. Instead the seeder writes absolute URLs
    /// under this base, which the Development host serves from
    /// <see cref="AssetsPath"/>, and production object storage is never touched.
    /// </summary>
    public string MediaBaseUrl { get; init; } = "http://localhost:5281";

    /// <summary>
    /// Folder holding the prepared demo images, relative to the API content root
    /// unless rooted. Generated by <c>marketing/demo/scripts/prepare-assets.mjs</c>.
    /// </summary>
    public string AssetsPath { get; init; } = "../../../marketing/demo/assets";

    /// <summary>The request path the Development host serves <see cref="AssetsPath"/> at.</summary>
    public string MediaRequestPath { get; init; } = "/dev-marketing-media";

    public static void ValidateForStartup(IHostEnvironment environment, MarketingDemoOptions options)
    {
        if (!options.Enabled)
        {
            return;
        }

        if (!environment.IsDevelopment())
        {
            throw new InvalidOperationException(
                $"{SectionName}:Enabled may only be true when the application environment is Development.");
        }

        if (!Uri.TryCreate(options.MediaBaseUrl, UriKind.Absolute, out var mediaBase)
            || (mediaBase.Scheme != Uri.UriSchemeHttp && mediaBase.Scheme != Uri.UriSchemeHttps))
        {
            throw new InvalidOperationException(
                $"{SectionName}:MediaBaseUrl must be an absolute http(s) URL.");
        }

        if (!mediaBase.IsLoopback)
        {
            // The whole point of the separate base is to keep fixtures off the
            // real CDN. A non-loopback value has either been pointed at a
            // deployed host or at production media, and both are wrong.
            throw new InvalidOperationException(
                $"{SectionName}:MediaBaseUrl must be a loopback address so demo media is never published.");
        }

        if (string.IsNullOrWhiteSpace(options.MediaRequestPath)
            || !options.MediaRequestPath.StartsWith('/'))
        {
            throw new InvalidOperationException(
                $"{SectionName}:MediaRequestPath must be a route beginning with '/'.");
        }
    }
}
